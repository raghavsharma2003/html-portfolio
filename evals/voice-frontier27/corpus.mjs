export function validateCorpus(items = corpus) {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  assert(items.length === 36, 'corpus must contain exactly 36 prompts');
  assert(new Set(items.map(x => x.id)).size === 36, 'duplicate prompt IDs');
  for (const language of ['English', 'Hindi', 'Hinglish']) {
    const rows = items.filter(x => x.language === language);
    assert(rows.length === 12, `${language}: require 12 prompts`);
    assert(rows.filter(x => x.split === 'dev').length === 3, `${language}: require 3 dev prompts`);
    assert(rows.filter(x => x.split === 'heldout').length === 9, `${language}: require 9 heldout prompts`);
  }
  for (const item of items) {
    assert(/^(en|hi|hx)\d{2}$/.test(item.id), 'invalid prompt ID');
    assert(['Latin', 'Devanagari', 'Devanagari+Latin'].includes(item.script), `${item.id}: invalid script`);
    assert(item.text.trim().length > 30 && item.intended_delivery && item.pronunciation_notes, `${item.id}: missing authored content`);
    assert(item.tags.length >= 2, `${item.id}: tags absent`);
    const [min, max] = item.target_duration_seconds;
    assert(min > 0 && max > min && max <= 30, `${item.id}: invalid duration target`);
    assert(item.language !== 'Hindi' || (item.script === 'Devanagari' && !/[A-Za-z]/.test(item.text)), `${item.id}: Hindi script mismatch`);
    assert(item.script !== 'Latin' || !/[\u0900-\u097f]/.test(item.text), `${item.id}: Latin script mismatch`);
    assert(item.script !== 'Devanagari+Latin' || (/[A-Za-z]/.test(item.text) && /[\u0900-\u097f]/.test(item.text)), `${item.id}: mixed script mismatch`);
  }
  return { prompts: 36, development: 9, heldout: 27, language_counts: { English: 12, Hindi: 12, Hinglish: 12 } };
}
