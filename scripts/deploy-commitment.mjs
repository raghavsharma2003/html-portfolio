#!/usr/bin/env node
// Stable release identity for deployment verification.
//
// Vite chunk names are environment-sensitive: changing a public build-time
// variable can change a filename even when the source release is correct. A
// verifier that compares that filename to a different local build therefore
// produces false stale-deploy alarms. This commitment hashes the source inputs
// that produce the Vercel web/API release instead. The Vercel build publishes
// the result and the post-deploy probe computes it again from the same checkout.

import { createHash } from "node:crypto";
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const DEPLOY_COMMITMENT_SCHEMA = 1;
export const DEPLOY_PRODUCTS = Object.freeze(["vyakti-clone", "meera-companion"]);

const DIRECTORY_INPUTS = Object.freeze(["api", "assets", "public", "site", "src"]);
const FILE_INPUTS = Object.freeze([
  ".vercelignore",
  "android/app/build.gradle",
  "capacitor.config.ts",
  "index.html",
  "package-lock.json",
  "package.json",
  "studio-layout-fixture.html",
  "studio.html",
  "tsconfig.app.json",
  "tsconfig.json",
  "tsconfig.node.json",
  "vercel.json",
  "vite.config.ts",
  "scripts/deploy-commitment.mjs",
  "scripts/deploy-vercel.mjs",
  "scripts/ota-bundle.mjs",
  "scripts/vercel-install.sh",
  "scripts/vercel-build.sh",
  "scripts/vercel-product.mjs",
  "scripts/write-deploy-marker.mjs",
  "scripts/write-config.mjs",
]);

const NEVER_HASH = new Set([
  // Vercel's uploader consumes nested ignore files but does not send the
  // control files themselves. Hashing them locally would make an identical
  // upload look stale by exactly those files.
  "src/engine/__fixtures__/.gitignore",
  "src/engine/agents/.gitignore",
  // These two ignored bundles are regenerated by release/build gates. They
  // are derived artifacts, not deployment source, and their environment-
  // specific bytes must not become part of the source commitment.
  "src/engine/__fixtures__/.bundle.mjs",
  "src/engine/agents/.eval-bundle.mjs",
  "api/_config.js",
  "api/_config.env",
  "api/keyring.json",
  "api/google-keys.env",
]);

const byteSort = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const portable = (path) => path.split(sep).join("/");

function collectDirectory(root, directory, output) {
  const absolute = resolve(root, directory);
  const stat = lstatSync(absolute);
  if (!stat.isDirectory()) throw new Error(`deployment input is not a directory: ${directory}`);
  for (const name of readdirSync(absolute).sort(byteSort)) {
    const childAbsolute = resolve(absolute, name);
    const childRelative = portable(relative(root, childAbsolute));
    const childStat = lstatSync(childAbsolute);
    if (childStat.isSymbolicLink()) {
      throw new Error(`deployment commitment refuses symbolic link: ${childRelative}`);
    }
    if (childStat.isDirectory()) collectDirectory(root, childRelative, output);
    else if (childStat.isFile() && !NEVER_HASH.has(childRelative)) output.push(childRelative);
  }
}

export function deploymentInputs(root) {
  const files = [];
  for (const directory of DIRECTORY_INPUTS) collectDirectory(root, directory, files);
  for (const file of FILE_INPUTS) {
    const stat = lstatSync(resolve(root, file));
    if (!stat.isFile()) throw new Error(`deployment input is not a file: ${file}`);
    files.push(file);
  }
  return [...new Set(files)].sort(byteSort);
}

export function createDeploymentRelease(root, product) {
  if (!DEPLOY_PRODUCTS.includes(product)) {
    throw new Error(`unknown deployment product ${JSON.stringify(product)}`);
  }
  const files = deploymentInputs(root);
  const hash = createHash("sha256");
  let byteCount = 0;
  for (const file of files) {
    const bytes = readFileSync(resolve(root, file));
    byteCount += bytes.length;
    hash.update(`${Buffer.byteLength(file)}:${file}\0${bytes.length}:`);
    hash.update(bytes);
    hash.update("\0");
  }
  return Object.freeze({
    schema: DEPLOY_COMMITMENT_SCHEMA,
    product,
    source_commitment: `sha256:${hash.digest("hex")}`,
    input_files: files.length,
    input_bytes: byteCount,
  });
}

function valueAfter(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : null;
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const product = valueAfter("--product") || "vyakti-clone";
  const output = valueAfter("--write");
  const release = createDeploymentRelease(root, product);
  if (output) {
    const absolute = resolve(root, output);
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, `${JSON.stringify(release, null, 2)}\n`, "utf8");
    console.log(`wrote ${portable(relative(root, absolute))} (${release.source_commitment})`);
  } else {
    console.log(JSON.stringify(release, null, 2));
  }
}
